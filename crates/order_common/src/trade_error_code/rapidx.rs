pub fn describe_error_code(code: i32) -> Option<&'static str> {
    DOCUMENTED_ERROR_CODES
        .binary_search_by_key(&code, |(documented, _)| *documented)
        .ok()
        .map(|index| DOCUMENTED_ERROR_CODES[index].1)
}

pub fn describe_http_status(status: u16) -> Option<&'static str> {
    match status {
        400 => Some("Bad request or business validation failure"),
        404 => Some("Endpoint not found"),
        405 => Some("HTTP method not allowed"),
        429 => Some("HTTP request rate limit exceeded"),
        500 => Some("Internal server error"),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_unique_and_every_entry_resolves() {
        for pair in DOCUMENTED_ERROR_CODES.windows(2) {
            assert!(pair[0].0 < pair[1].0, "RapidX error table is not sorted");
        }
        for (code, description) in DOCUMENTED_ERROR_CODES {
            assert_eq!(describe_error_code(*code), Some(*description));
        }
    }

    #[test]
    fn maps_observed_order_errors_and_unknown_code() {
        assert_eq!(
            describe_error_code(401055),
            Some("Insufficient available balance")
        );
        assert_eq!(
            describe_error_code(401071),
            Some("Order quantity must be a multiple of lotSize")
        );
        assert_eq!(describe_error_code(999999), None);
    }
}
